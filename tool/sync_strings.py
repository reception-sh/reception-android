#!/usr/bin/env python3
"""Generate the SDK's Android string resources from the iOS String Catalog.

Reads reception-ios/Sources/Reception/Resources/Localizable.xcstrings and writes
reception/src/main/res/values*/strings.xml plus reception/src/main/kotlin/sh/reception/Strings.kt.

Usage:
    tool/sync_strings.py [--catalog PATH]          write the files
    tool/sync_strings.py [--catalog PATH] --check  exit 1 when the files on disk differ
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CATALOG = ROOT.parent / "reception-ios/Sources/Reception/Resources/Localizable.xcstrings"
RES = ROOT / "reception/src/main/res"
KOTLIN = ROOT / "reception/src/main/kotlin/sh/reception/Strings.kt"
HEADER = "Generated by tool/sync_strings.py from the iOS String Catalog; do not edit."
PREFIX = "reception_"
MAX_NAME = 40

# iOS language identifier -> Android resource qualifiers (SPEC.md, Language).
QUALIFIERS = {
    "de": ["de"], "fr": ["fr"], "fr-CA": ["fr-rCA"], "es": ["es"], "es-419": ["b+es+419"],
    "it": ["it"], "pt-BR": ["pt-rBR"], "pt-PT": ["pt-rPT"], "ca": ["ca"], "ro": ["ro"],
    "nl": ["nl"], "sv": ["sv"], "da": ["da"], "nb": ["nb"], "fi": ["fi"], "pl": ["pl"],
    "cs": ["cs"], "sk": ["sk"], "hu": ["hu"], "sl": ["sl"], "hr": ["hr"], "el": ["el"],
    "uk": ["uk"], "ru": ["ru"], "tr": ["tr"], "ja": ["ja"], "ko": ["ko"],
    "zh-Hans": ["b+zh+Hans"], "zh-Hant": ["b+zh+Hant"], "zh-HK": ["b+zh+Hant+HK"],
    "th": ["th"], "vi": ["vi"], "id": ["in", "b+id"], "ms": ["ms"], "hi": ["hi"],
    "bn": ["bn"], "gu": ["gu"], "kn": ["kn"], "ml": ["ml"], "mr": ["mr"], "or": ["or"],
    "pa": ["pa"], "ta": ["ta"], "te": ["te"], "ur": ["ur"], "ar": ["ar"], "he": ["iw", "b+he"],
}
# Kotlin hard keywords cannot name a property without backticks.
KOTLIN_KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
    "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof",
    "val", "var", "when", "while",
}
QUANTITIES = ["zero", "one", "two", "few", "many", "other"]
SPECIFIER = re.compile(r"%(?:(\d+)\$)?(@|lld|ld|lu|llu|d|i|u)|%%")


def fail(message):
    print(f"sync_strings: {message}", file=sys.stderr)
    sys.exit(2)


def resource_name(source):
    words = re.sub(r"[^a-z0-9]+", " ", SPECIFIER.sub(" ", source).replace("'", "").replace("’", "").lower()).split()
    name = ""
    for word in words:
        candidate = f"{name}_{word}" if name else word
        if len(candidate) > MAX_NAME:
            break
        name = candidate
    return name


def assign_names(sources):
    """Snake-case names from the English source; a colliding source other than the shortest gets a hash suffix."""
    groups = {}
    for source in sorted(sources):
        groups.setdefault(resource_name(source), []).append(source)
    names = {}
    for base, members in groups.items():
        if not base:
            fail(f"no resource name derivable from {members!r}")
        members.sort(key=lambda value: (len(value), value))
        names[members[0]] = base
        for source in members[1:]:
            names[source] = f"{base}_{hashlib.sha1(source.encode()).hexdigest()[:6]}"
    if len(set(names.values())) != len(names):
        fail("resource names collide after hashing")
    return names


def convert_format(text, context):
    position = 0

    def replace(match):
        nonlocal position
        if match.group(0) == "%%":
            return "%%"
        if match.group(1):
            index = int(match.group(1))
        else:
            position += 1
            index = position
        kind = "s" if match.group(2) == "@" else "d"
        return f"%{index}${kind}"

    converted = SPECIFIER.sub(replace, text)
    leftover = re.sub(r"%\d+\$[sd]|%%", "", converted)
    if "%" in leftover:
        fail(f"unsupported format specifier in {context}: {text!r}")
    return converted


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    if text != text.strip():
        text = f'"{text}"'
    return text


def localized_value(entry, language, source):
    unit = entry.get("localizations", {}).get(language)
    if unit is None:
        fail(f"{source!r} has no {language} localization")
    if "stringUnit" in unit:
        return unit["stringUnit"]["value"]
    plural = unit.get("variations", {}).get("plural")
    if plural is None:
        fail(f"{source!r} ({language}) has an unsupported variation")
    return {quantity: plural[quantity]["stringUnit"]["value"] for quantity in QUANTITIES if quantity in plural}


def strings_xml(catalog, names, language):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
    for source in sorted(names, key=lambda value: names[value]):
        name = PREFIX + names[source]
        value = localized_value(catalog[source], language, source)
        context = f"{source!r} ({language})"
        # Languages without plural forms store a single string; Android needs the plurals resource everywhere.
        if isinstance(value, str) and isinstance(localized_value(catalog[source], "en", source), dict):
            value = {"other": value}
        if isinstance(value, str):
            lines.append(f'    <string name="{name}">{escape(convert_format(value, context))}</string>')
            continue
        lines.append(f'    <plurals name="{name}">')
        for quantity, text in value.items():
            lines.append(f'        <item quantity="{quantity}">{escape(convert_format(text, context))}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def camel_case(name):
    first, *rest = name.split("_")
    camel = first + "".join(part[:1].upper() + part[1:] for part in rest)
    return camel + "Text" if camel in KOTLIN_KEYWORDS else camel


def kotlin_source(catalog, names):
    strings, plurals = [], []
    for source in sorted(names, key=lambda value: names[value]):
        plural = isinstance(localized_value(catalog[source], "en", source), dict)
        target = plurals if plural else strings
        kind = "plurals" if plural else "string"
        comment = source.replace("*/", "* /")
        target.append(f'    /** "{comment}" */')
        target.append(f"    val {camel_case(names[source])}: Int = R.{kind}.{PREFIX}{names[source]}")
    lines = [
        f"// {HEADER}",
        "package sh.reception",
        "",
        "/** Resource IDs of the SDK's built-in strings, named after their English source text. */",
        "internal object Strings {",
        *strings,
        "",
        "    /** Quantity strings, read with `ReceptionLocalization.plural`. */",
        "    object Plurals {",
        *["    " + line for line in plurals],
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def outputs(catalog_path):
    try:
        document = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        fail(f"cannot read {catalog_path}: {error}")
    if document.get("sourceLanguage") != "en":
        fail("the catalog's source language is not English")
    # Entries without localizations are not user-facing strings (Xcode extracted them from verbatim text).
    catalog = {key: value for key, value in document["strings"].items() if value.get("localizations")}
    names = assign_names(catalog)
    files = {RES / "values/strings.xml": strings_xml(catalog, names, "en")}
    for language, qualifiers in QUALIFIERS.items():
        for qualifier in qualifiers:
            files[RES / f"values-{qualifier}/strings.xml"] = strings_xml(catalog, names, language)
    files[KOTLIN] = kotlin_source(catalog, names)
    return files


def stale(files):
    """Generated string files on disk that this run would not produce."""
    return [path for path in RES.glob("values*/strings.xml") if path not in files and HEADER in path.read_text("utf-8")]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    parser.add_argument("--check", action="store_true", help="fail when the generated files would change")
    arguments = parser.parse_args()
    files = outputs(arguments.catalog)
    changed = [path for path, text in files.items() if not path.exists() or path.read_text("utf-8") != text]
    removed = stale(files)
    if arguments.check:
        for path in changed + removed:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        if changed or removed:
            print("run tool/sync_strings.py", file=sys.stderr)
            return 1
        print(f"strings up to date ({len(files)} files)")
        return 0
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8")
    for path in removed:
        path.unlink()
    print(f"wrote {len(changed)} of {len(files)} files, removed {len(removed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
