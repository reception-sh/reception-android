#!/usr/bin/env python3
"""Generate the SDK's built-in strings as Kotlin from the iOS String Catalog.

Reads reception-ios/Sources/Reception/Resources/Localizable.xcstrings plus tool/android-strings.json (the strings
only Android shows) and writes reception/src/main/kotlin/sh/reception/strings/: one `internal object` per language
(`De.kt`, `FrCA.kt`, `ZhHant.kt`, ...) and `Strings.kt` with the stable keys and the language registry. Strings are
Kotlin rather than Android resources so App Bundle language splits can never strip a language (SPEC.md, Language).

Usage:
    tool/sync_strings.py [--catalog PATH]          write the files
    tool/sync_strings.py [--catalog PATH] --check  exit 1 when the files on disk differ
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CATALOG = ROOT.parent / "reception-ios/Sources/Reception/Resources/Localizable.xcstrings"
OVERLAY = ROOT / "tool/android-strings.json"
OUTPUT = ROOT / "reception/src/main/kotlin/sh/reception/strings"
HEADER = "Generated by tool/sync_strings.py from the iOS String Catalog; do not edit."
MAX_NAME = 40

# The 48 bundled languages (SPEC.md, Language), in the iOS order.
LANGUAGES = [
    "en", "de", "fr", "fr-CA", "es", "es-419", "it", "pt-BR", "pt-PT", "ca", "ro", "nl",
    "sv", "da", "nb", "fi", "pl", "cs", "sk", "hu", "sl", "hr", "el", "uk", "ru", "tr",
    "ja", "ko", "zh-Hans", "zh-Hant", "zh-HK", "th", "vi", "id", "ms", "hi", "bn", "gu",
    "kn", "ml", "mr", "or", "pa", "ta", "te", "ur", "ar", "he",
]
# Kotlin hard keywords cannot name a property without backticks.
KOTLIN_KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
    "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof",
    "val", "var", "when", "while",
}
CATEGORIES = ["zero", "one", "two", "few", "many", "other"]
SPECIFIER = re.compile(r"%(?:(\d+)\$)?(@|lld|ld|lu|llu|d|i|u)|%%")


def fail(message):
    print(f"sync_strings: {message}", file=sys.stderr)
    sys.exit(2)


def key_name(source):
    words = re.sub(r"[^a-z0-9]+", " ", SPECIFIER.sub(" ", source).replace("'", "").replace("’", "").lower()).split()
    name = ""
    for word in words:
        candidate = f"{name}_{word}" if name else word
        if len(candidate) > MAX_NAME:
            break
        name = candidate
    return name


def assign_keys(sources):
    """Snake-case keys from the English source; a colliding source other than the shortest gets a hash suffix."""
    groups = {}
    for source in sorted(sources):
        groups.setdefault(key_name(source), []).append(source)
    keys = {}
    for base, members in groups.items():
        if not base:
            fail(f"no key derivable from {members!r}")
        members.sort(key=lambda value: (len(value), value))
        keys[members[0]] = base
        for source in members[1:]:
            keys[source] = f"{base}_{hashlib.sha1(source.encode()).hexdigest()[:6]}"
    if len(set(keys.values())) != len(keys):
        fail("keys collide after hashing")
    return keys


def convert_format(text, context):
    """iOS specifiers to `String.format` ones: `%@` -> `%1$s`, `%lld` -> `%1$d`."""
    position = 0

    def replace(match):
        nonlocal position
        if match.group(0) == "%%":
            return "%%"
        if match.group(1):
            index = int(match.group(1))
        else:
            position += 1
            index = position
        kind = "s" if match.group(2) == "@" else "d"
        return f"%{index}${kind}"

    converted = SPECIFIER.sub(replace, text)
    leftover = re.sub(r"%\d+\$[sd]|%%", "", converted)
    if "%" in leftover:
        fail(f"unsupported format specifier in {context}: {text!r}")
    return converted


def literal(text):
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    escaped = escaped.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f'"{escaped}"'


def localized_value(entry, language, source):
    unit = entry.get("localizations", {}).get(language)
    if unit is None:
        fail(f"{source!r} has no {language} localization")
    if "stringUnit" in unit:
        return unit["stringUnit"]["value"]
    plural = unit.get("variations", {}).get("plural")
    if plural is None:
        fail(f"{source!r} ({language}) has an unsupported variation")
    return {category: plural[category]["stringUnit"]["value"] for category in CATEGORIES if category in plural}


def object_name(language):
    first, *rest = language.split("-")
    return first[:1].upper() + first[1:] + "".join(rest)


def constant_name(key):
    first, *rest = key.split("_")
    camel = first + "".join(part[:1].upper() + part[1:] for part in rest)
    return camel + "Text" if camel in KOTLIN_KEYWORDS else camel


class Table:
    """Every string as `key -> {language: value}`, plural values as `{category: text}`."""

    def __init__(self, catalog, overlay):
        keys = assign_keys(catalog)
        self.english = {}
        self.values = {}
        self.plural = set()
        for source, key in keys.items():
            self.english[key] = source
            if isinstance(localized_value(catalog[source], "en", source), dict):
                self.plural.add(key)
            self.values[key] = {language: localized_value(catalog[source], language, source) for language in LANGUAGES}
        for key, translations in overlay.items():
            if key in self.values:
                fail(f"overlay key {key!r} is already a catalog key")
            missing = [language for language in LANGUAGES if not translations.get(language)]
            if missing:
                fail(f"overlay key {key!r} has no {', '.join(missing)} translation")
            self.english[key] = translations["en"]
            self.values[key] = {language: translations[language] for language in LANGUAGES}

    def keys(self, plural):
        return sorted(key for key in self.values if (key in self.plural) == plural)

    def plural_forms(self, key, language):
        value = self.values[key][language]
        # Languages without plural forms store a single string.
        return value if isinstance(value, dict) else {"other": value}


def language_source(table, language):
    context = lambda key: f"{table.english[key]!r} ({language})"
    lines = [
        f"// {HEADER}",
        "package sh.reception.strings",
        "",
        f"internal object {object_name(language)} : LanguageTable {{",
        "    override val strings: Map<String, String> = mapOf(",
    ]
    for key in table.keys(plural=False):
        text = convert_format(table.values[key][language], context(key))
        lines.append(f"        Strings.{constant_name(key)} to {literal(text)},")
    lines.append("    )")
    lines.append("    override val plurals: Map<String, Map<String, String>> = mapOf(")
    for key in table.keys(plural=True):
        lines.append(f"        Strings.Plurals.{constant_name(key)} to mapOf(")
        for category, text in table.plural_forms(key, language).items():
            lines.append(f"            {literal(category)} to {literal(convert_format(text, context(key)))},")
        lines.append("        ),")
    lines.append("    )")
    lines.append("}")
    return "\n".join(lines) + "\n"


def strings_source(table):
    def constants(plural, indent):
        lines = []
        for key in table.keys(plural):
            comment = table.english[key].replace("*/", "* /")
            lines.append(f'{indent}/** "{comment}" */')
            lines.append(f"{indent}const val {constant_name(key)}: String = {literal(key)}")
        return lines

    lines = [
        f"// {HEADER}",
        "package sh.reception.strings",
        "",
        "/** One language's built-in strings, keyed by the [Strings] constants. */",
        "internal interface LanguageTable {",
        "    val strings: Map<String, String>",
        "",
        "    /** Plural forms by CLDR category: `zero`, `one`, `two`, `few`, `many`, `other`. */",
        "    val plurals: Map<String, Map<String, String>>",
        "}",
        "",
        "/** Stable keys of the SDK's built-in strings, named after their English text. */",
        "internal object Strings {",
        *constants(False, "    "),
        "",
        "    /** Quantity strings, read with `ReceptionLocalization.plural`. */",
        "    object Plurals {",
        *constants(True, "        "),
        "    }",
        "",
        "    /** The 48 bundled languages by their SDK tag. */",
        "    val languages: Map<String, LanguageTable> = mapOf(",
        *[f"        {literal(language)} to {object_name(language)}," for language in LANGUAGES],
        "    )",
        "}",
    ]
    return "\n".join(lines) + "\n"


def outputs(catalog_path):
    try:
        document = json.loads(catalog_path.read_text(encoding="utf-8"))
        overlay = json.loads(OVERLAY.read_text(encoding="utf-8"))["strings"]
    except (OSError, ValueError, KeyError) as error:
        fail(f"cannot read the string sources: {error}")
    if document.get("sourceLanguage") != "en":
        fail("the catalog's source language is not English")
    # Entries without localizations are not user-facing strings (Xcode extracted them from verbatim text).
    catalog = {key: value for key, value in document["strings"].items() if value.get("localizations")}
    table = Table(catalog, overlay)
    files = {OUTPUT / "Strings.kt": strings_source(table)}
    for language in LANGUAGES:
        files[OUTPUT / f"{object_name(language)}.kt"] = language_source(table, language)
    return files


def stale(files):
    """Generated files on disk that this run would not produce."""
    return [path for path in OUTPUT.glob("*.kt") if path not in files and HEADER in path.read_text("utf-8")]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    parser.add_argument("--check", action="store_true", help="fail when the generated files would change")
    arguments = parser.parse_args()
    files = outputs(arguments.catalog)
    changed = [path for path, text in files.items() if not path.exists() or path.read_text("utf-8") != text]
    removed = stale(files)
    if arguments.check:
        for path in changed + removed:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        if changed or removed:
            print("run tool/sync_strings.py", file=sys.stderr)
            return 1
        print(f"strings up to date ({len(files)} files)")
        return 0
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8")
    for path in removed:
        path.unlink()
    print(f"wrote {len(changed)} of {len(files)} files, removed {len(removed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
